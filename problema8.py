def max_adjacent_product(digits, num_digits):
    max_product = 0

    for i in range(len(digits) - num_digits + 1):
        product = 1
        for j in range(num_digits):
            product *= int(digits[i + j])
        
        if product > max_product:
            max_product = product
    
    return max_product, digits[i:i + num_digits]

